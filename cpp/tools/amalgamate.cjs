// Fold the vendored dependencies into one self-contained chamina.h.
//
//   node cpp/tools/amalgamate.cjs        → dist/chamina.h (self-contained)
//
// The src header resolves its four vendored includes through -Icpp/vendor;
// this tool replaces each `#include "…"` line inside the IMPLEMENTATION block
// with the full text of the vendored file. The output needs nothing but the
// C++ standard library, so a host project can drop a single file into its
// tree. Re-run after editing cpp/src/chamina.h or the vendor headers.
const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..', '..');
const srcPath = path.join(root, 'cpp/src/chamina.h');
const outDir = path.join(root, 'dist');
const outPath = path.join(outDir, 'chamina.h');

const src = fs.readFileSync(srcPath, 'utf8');
// The header mixes line endings (banner/API half is LF, the engine body
// came through CRLF). Split on '\n' and keep each line's trailing '\r' —
// splicing and rejoining is then byte-preserving for both halves.
const lines = src.split('\n');

// The four includes only exist inside the IMPLEMENTATION block (the API half
// of the header includes nothing but standard headers), so a global replace
// per exact line is safe and order-preserving.
const folds = [
  ['json.hpp', 'nlohmann/json.hpp — JSON parse/serialise (MIT)'],
  ['earcut.hpp', 'mapbox/earcut.hpp — polygon triangulation (ISC)'],
  ['stb_truetype.h', 'stb_truetype.h — TrueType glyph outlines (public domain)'],
  ['stb_image_write.h', 'stb_image_write.h — PNG encoding (public domain)'],
];

const banner =
  '// === AMALGAMATION — generated by cpp/tools/amalgamate.cjs; edit\n' +
  '// cpp/src/chamina.h (or the vendored headers) and regenerate, never edit\n' +
  '// this file by hand. Below, the four vendored third-party headers are\n' +
  '// inlined verbatim where the src header includes them:\n';

for (const [file, desc] of folds) {
  const inc = `#include "${file}"`;
  const idx = lines.findIndex((l) => l.trim() === inc);
  if (idx < 0) throw new Error(`include line not found: ${inc}`);
  const vendTxt = fs.readFileSync(path.join(root, 'cpp/vendor', file), 'utf8');
  const vend = vendTxt.split('\n');
  const block = [
    `// --- begin ${desc} (vendored ${file}, inlined verbatim) ---`,
    ...vend,
    `// --- end ${file} ---`,
    '',
  ];
  lines.splice(idx, 1, ...block);
}

const out = banner + lines.join('\n');
fs.mkdirSync(outDir, { recursive: true });
fs.writeFileSync(outPath, out);
const srcLines = src.split('\n').length;
console.log(
  `wrote ${path.relative(root, outPath)}: ${out.split('\n').length} lines ` +
  `(src ${srcLines} lines + 4 vendored folds)`
);
